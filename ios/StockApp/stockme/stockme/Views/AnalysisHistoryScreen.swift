import SwiftUI
import Charts

struct HistoricalSignal: Identifiable {
    let id = UUID()
    let date: Date
    let signal: Signal
    let price: Double
}

struct AnalysisHistoryTimelineView: View {
    let ticker: String
    let priceHistory: [PricePoint]
    
    @State private var signals: [HistoricalSignal] = []
    
    var body: some View {
        VStack(alignment: .leading, spacing: Theme.Spacing.standard) {
            if priceHistory.isEmpty {
                Text("Price history not available")
                    .font(Theme.engravedSerif(size: 14, weight: .regular, relativeTo: .body))
                    .foregroundStyle(Theme.inkSecondary)
                    .frame(maxWidth: .infinity, alignment: .center)
                    .frame(height: 200)
            } else {
                Chart {
                    ForEach(priceHistory) { p in
                        LineMark(
                            x: .value("Date", p.parsedDate),
                            y: .value("Price", p.close)
                        )
                        .foregroundStyle(Theme.inkPrimary)
                        .interpolationMethod(.catmullRom)
                    }
                    
                    ForEach(signals) { s in
                        PointMark(
                            x: .value("Date", s.date),
                            y: .value("Price", s.price)
                        )
                        .symbol {
                            VStack(spacing: Theme.Spacing.xSmall) {
                                Text(s.signal == .bullish ? "BUY" : (s.signal == .bearish ? "SELL" : "HOLD"))
                                    .font(Theme.officialStampFont(size: 8))
                                    .foregroundStyle(Theme.inkPrimary)
                                    .padding(.horizontal, 4)
                                    .background(s.signal == .bullish ? Theme.bullGreen.opacity(0.8) : Theme.bearRed.opacity(0.8))
                                    .clipShape(Capsule())
                                
                                Image(systemName: s.signal == .bullish ? "arrow.up.circle.fill" : "arrow.down.circle.fill")
                                    .foregroundStyle(s.signal == .bullish ? Theme.bullGreen : Theme.bearRed)
                                    .background(Circle().fill(Theme.canvasDeep))
                            }
                        }
                    }
                }
                .frame(height: 200)
                .chartXAxis {
                    AxisMarks(values: .automatic(desiredCount: 5)) {
                        AxisValueLabel(format: .dateTime.month(.abbreviated))
                            .font(Theme.officialStampFont(size: 9))
                            .foregroundStyle(Theme.inkTertiary)
                    }
                }
                .chartYAxis {
                    AxisMarks(values: .automatic(desiredCount: 4)) {
                        AxisGridLine().foregroundStyle(Theme.borderFine)
                        AxisValueLabel()
                            .font(Theme.officialStampFont(size: 9))
                            .foregroundStyle(Theme.inkTertiary)
                    }
                }
            }
            
            Text("Historical signals generated by Nivesh AI overlaid on the actual stock price. Past performance is not indicative of future results.")
                .font(Theme.engravedSerif(size: 11, weight: .regular, relativeTo: .caption2))
                .foregroundStyle(Theme.inkTertiary)
                .lineSpacing(2)
        }
        .padding(Theme.Spacing.card)
        .background(Theme.surfaceElevated)
        .clipShape(RoundedRectangle(cornerRadius: Theme.CornerRadius.card))
        .overlay(RoundedRectangle(cornerRadius: Theme.CornerRadius.card).stroke(Theme.borderSubtle, lineWidth: 0.5))
        .onAppear {
            generateMockSignals()
        }
    }
    
    private func generateMockSignals() {
        guard !priceHistory.isEmpty else { return }
        
        var mock: [HistoricalSignal] = []
        let count = priceHistory.count
        
        // Mock a bullish signal roughly 60 days ago
        if count > 40 {
            let p1 = priceHistory[count - 40]
            mock.append(HistoricalSignal(date: p1.parsedDate, signal: .bullish, price: p1.close))
        }
        
        // Mock a bearish signal roughly 15 days ago
        if count > 15 {
            let p2 = priceHistory[count - 15]
            mock.append(HistoricalSignal(date: p2.parsedDate, signal: .bearish, price: p2.close))
        }
        
        self.signals = mock
    }
}
